/**
 * PDF Export Utilities
 * Generate professional PDF reports for compliance documentation
 */

export interface PDFReportConfig {
  title: string
  subtitle?: string
  organizationName: string
  generatedBy: string
  generatedAt: Date
  dateRange?: {
    from: Date
    to: Date
  }
  logo?: string
}

export interface PDFSection {
  heading: string
  content: string | string[] | Record<string, any>
  type?: 'text' | 'table' | 'chart' | 'list'
}

