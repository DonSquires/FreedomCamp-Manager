function renderSection(section: PDFSection): string {
  switch (section.type) {
    case 'table':
      return renderTableSection(section)
    case 'list':
      return renderListSection(section)
    default:
      return renderTextSection(section)
  }
}

function renderTextSection(section: PDFSection): string {
  const content = Array.isArray(section.content) 
    ? section.content.join('<br>') 
    : typeof section.content === 'string'
    ? section.content
    : JSON.stringify(section.content, null, 2)

  return `
    <div class="section">
      <h2>${section.heading}</h2>
      <p>${content}</p>
    </div>
  `
}

function renderListSection(section: PDFSection): string {
  const items = Array.isArray(section.content) ? section.content : [section.content]
  
  return `
    <div class="section">
      <h2>${section.heading}</h2>
      <ul>
        ${items.map(item => `<li>${item}</li>`).join('\n')}
      </ul>
    </div>
  `
}

function renderTableSection(section: PDFSection): string {
  if (!Array.isArray(section.content)) {
    return renderTextSection(section)
  }

  const rows = section.content as any[]
  if (rows.length === 0) {
    return `
      <div class="section">
        <h2>${section.heading}</h2>
        <p>No data available.</p>
      </div>
    `
  }

  const headers = Object.keys(rows[0])
  
  return `
    <div class="section">
      <h2>${section.heading}</h2>
      <table>
        <thead>
          <tr>
            ${headers.map(h => `<th>${formatHeaderName(h)}</th>`).join('')}
          </tr>
        </thead>
        <tbody>
          ${rows.map(row => `
            <tr>
              ${headers.map(h => `<td>${formatCellValue(row[h])}</td>`).join('')}
            </tr>
          `).join('')}
        </tbody>
      </table>
    </div>
  `
}

function formatHeaderName(name: string): string {
  return name
    .replace(/_/g, ' ')
    .replace(/\b\w/g, l => l.toUpperCase())
}

function formatCellValue(value: any): string {
  if (value === null || value === undefined) return '-'
  if (typeof value === 'boolean') return value ? 'Yes' : 'No'
  if (value instanceof Date) return formatDate(value)
  return String(value)
}

function formatDate(date: Date): string {
  return date.toLocaleDateString('en-NZ', {
    year: 'numeric',
    month: 'short',
    day: 'numeric',
    timeZone: 'Pacific/Auckland'
  })
}

function formatDateTime(date: Date): string {
  return date.toLocaleString('en-NZ', {
    year: 'numeric',
    month: 'short',
    day: 'numeric',
    hour: '2-digit',
    minute: '2-digit',
    timeZone: 'Pacific/Auckland'
  })
}

/**
 * Export report as PDF using browser print dialog
 */
export function exportReportPDF(
  config: PDFReportConfig,
  sections: PDFSection[]
): void {
  const html = generateReportHTML(config, sections)
  
  // Create new window
  const printWindow = window.open('', '_blank')
  if (!printWindow) {
    throw new Error('Failed to open print window. Please allow popups.')
  }

  // Write HTML
  printWindow.document.write(html)
  printWindow.document.close()

  // Wait for load, then print
  printWindow.onload = () => {
    printWindow.focus()
    printWindow.print()
  }
}

/**
 * Generate compliance summary report
 */
export async function exportComplianceReport(
  organizationName: string,
  generatedBy: string,
  dateRange: { from: Date; to: Date },
  data: {
    summary: Record<string, number>
    vehicles: any[]
    breaches: any[]
    zones: any[]
  }
): Promise<void> {
  const config: PDFReportConfig = {
    title: 'Compliance Summary Report',
    subtitle: 'Freedom Camping Compliance Analysis',
    organizationName,
    generatedBy,
    generatedAt: new Date(),
    dateRange,
  }

  const sections: PDFSection[] = [
    {
      heading: 'Executive Summary',
      content: [
        `Total Observations: ${data.summary.total_observations || 0}`,
        `Compliant: ${data.summary.compliant || 0} (${((data.summary.compliant / data.summary.total_observations) * 100).toFixed(1)}%)`,
        `Breaches: ${data.summary.breaches || 0}`,
        `Unique Vehicles: ${data.summary.unique_vehicles || 0}`,
        `Active Enforcement: ${data.summary.active_enforcement || 0}`,
      ],
      type: 'list'
    },
    {
      heading: 'Top Breach Vehicles',
      content: data.vehicles.slice(0, 10),
      type: 'table'
    },
    {
      heading: 'Zone Activity',
      content: data.zones,
      type: 'table'
    },
    {
      heading: 'Recent Breaches',
      content: data.breaches.slice(0, 20),
      type: 'table'
    },
  ]

  exportReportPDF(config, sections)
}
