#!/usr/bin/env node

/**
 * Pod-native Bob self-test
 *
 * Validates a Pod-hosted inference-service for:
 * 1) core health (/health)
 * 2) self-healing planner (/self-heal/bug-report)
 * 3) optional internal code executor kick (/code/executor/run)
 *
 * Required env:
 *   INFERENCE_SERVICE_URL (default: http://127.0.0.1:3000)
 * Optional auth env (needed for self-heal/executor checks):
 *   INFERENCE_API_KEY or RUNPOD_ENDPOINT_API_KEY or RUNPOD_API_KEY
 *
 * Optional flags:
 *   --skipExecutor true|false   (default: false)
 *   --timeoutMs <number>        (default: 45000)
 */

import process from 'node:process';

function getArg(name, fallback = '') {
  const key = `--${name}`;
  const args = process.argv.slice(2);
  for (let i = 0; i < args.length; i += 1) {
    const token = String(args[i] || '');
    if (token === key) return String(args[i + 1] || fallback);
    if (token.startsWith(`${key}=`)) return token.slice(key.length + 1) || fallback;
  }
  return fallback;
}

function getBoolArg(name, fallback = false) {
  const raw = String(getArg(name, String(fallback))).trim().toLowerCase();
  if (process.argv.includes(`--${name}`)) return true;
  return raw === '1' || raw === 'true' || raw === 'yes' || raw === 'on';
}

function normalizeBaseUrl(raw) {
  const trimmed = String(raw || '').trim().replace(/\/+$/, '');
  if (!trimmed) return '';
  return /^https?:\/\//i.test(trimmed) ? trimmed : `http://${trimmed}`;
}

async function fetchJson(url, options = {}, timeoutMs = 45000) {
  const controller = new AbortController();
  const timeoutId = setTimeout(() => controller.abort(), timeoutMs);
  try {
    const response = await fetch(url, { ...options, signal: controller.signal });
    const text = await response.text();
    let data = null;
    try {
      data = text ? JSON.parse(text) : null;
    } catch {
      data = { raw: text };
    }
    return { ok: response.ok, status: response.status, data };
  } finally {
    clearTimeout(timeoutId);
  }
}

async function main() {
  const baseUrl = normalizeBaseUrl(process.env.INFERENCE_SERVICE_URL || 'http://127.0.0.1:3000');
  const apiKey = String(
    process.env.INFERENCE_API_KEY ||
      process.env.RUNPOD_ENDPOINT_API_KEY ||
      process.env.RUNPOD_API_KEY ||
      ''
  ).trim();
  const timeoutMs = Number(getArg('timeoutMs', '45000')) || 45000;
  const skipExecutor = getBoolArg('skipExecutor', false);

  if (!baseUrl) {
    console.error('[pod-self-test] Missing INFERENCE_SERVICE_URL');
    process.exit(1);
  }

  const privilegedHeaders = apiKey
    ? {
        Authorization: `Bearer ${apiKey}`,
        'x-inference-api-key': apiKey,
        'Content-Type': 'application/json',
      }
    : {
        'Content-Type': 'application/json',
      };

  let failures = 0;

  // 1) Health check (no auth required)
  const health = await fetchJson(`${baseUrl}/health`, { method: 'GET' }, timeoutMs);
  const healthStatus = String(health?.data?.status || '').toLowerCase();
  const healthOk = health.ok && (healthStatus === 'healthy' || healthStatus === 'ok' || health.status === 200);
  console.log(`CHECK health ok=${healthOk} status=${health.status} service_status=${health?.data?.status || 'unknown'}`);
  if (!healthOk) failures += 1;

  // 2) Self-healing planner (requires auth)
  if (!apiKey) {
    console.log('CHECK self-heal skipped=true reason=no-api-key');
  } else {
    const selfHeal = await fetchJson(
      `${baseUrl}/self-heal/bug-report`,
      {
        method: 'POST',
        headers: privilegedHeaders,
        body: JSON.stringify({
          report: {
            summary: 'Pod self-test synthetic UI regression',
            description: 'Synthetic test report generated by trigger-bob-pod-self-test.mjs',
            severity: 'medium',
            issue_type: 'bug',
            current_page: '/bob-studio',
            steps_to_reproduce: 'Open Bob Studio voice tab and click PTT',
            actual_behavior: 'Synthetic self-test placeholder',
            expected_behavior: 'Self-healing planner returns valid structured plan',
          },
        }),
      },
      timeoutMs
    );

    const hasPlan = Boolean(selfHeal?.data?.plan);
    const selfHealOk = selfHeal.ok && selfHeal?.data?.success === true && hasPlan;
    console.log(
      `CHECK self-heal ok=${selfHealOk} status=${selfHeal.status} provider=${selfHeal?.data?.plan?.analysis_provider || 'unknown'}`
    );
    if (!selfHealOk) failures += 1;
  }

  // 3) Optional code executor trigger (requires auth)
  if (skipExecutor) {
    console.log('CHECK executor skipped=true reason=flag');
  } else if (!apiKey) {
    console.log('CHECK executor skipped=true reason=no-api-key');
  } else {
    const executor = await fetchJson(
      `${baseUrl}/code/executor/run`,
      {
        method: 'POST',
        headers: privilegedHeaders,
        body: JSON.stringify({ limit: 1 }),
      },
      timeoutMs
    );

    const executorOk = executor.ok && executor?.data?.success !== false;
    console.log(`CHECK executor ok=${executorOk} status=${executor.status}`);
    if (!executorOk) failures += 1;
  }

  if (failures > 0) {
    console.error(`SUMMARY failed=${failures}`);
    process.exit(1);
  }

  console.log('SUMMARY failed=0');
}

main().catch((error) => {
  console.error(`[pod-self-test] fatal: ${error?.message || error}`);
  process.exit(1);
});
