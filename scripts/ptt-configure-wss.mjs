#!/usr/bin/env node
/**
 * ptt-configure-wss.mjs
 *
 * Diagnostic + configuration helper for the PTT wss:// misconfiguration error.
 *
 * Problem: PTT_SERVER_URL is HTTP. The app runs on HTTPS. Browsers block mixed
 * content (ws:// from an https:// page). Result:
 *   "PTT misconfiguration: secure app requires wss:// signaling URL"
 *
 * Solution: front the PTT server with TLS using nginx + certbot, then set
 * PTT_WS_URL to the wss:// endpoint in Supabase secrets.
 *
 * Usage:
 *   node scripts/ptt-configure-wss.mjs
 *   node scripts/ptt-configure-wss.mjs --domain ptt.yourdomain.com
 *   node scripts/ptt-configure-wss.mjs --nginx-only
 */

import { execSync } from 'node:child_process';
import path from 'node:path';
import fs from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const args = process.argv.slice(2);

function getArg(flag) {
  const i = args.indexOf(flag);
  return i !== -1 && args[i + 1] ? args[i + 1] : null;
}

const domain = getArg('--domain') || process.env.PTT_DOMAIN || null;
const nginxOnly = args.includes('--nginx-only');

// ─── Read current PTT_SERVER_URL from system_state.json ─────────────────────
async function readSystemState() {
  try {
    const raw = await fs.readFile(path.resolve(__dirname, '..', 'system_state.json'), 'utf8');
    return JSON.parse(raw);
  } catch {
    return null;
  }
}

// ─── Build nginx config snippet ──────────────────────────────────────────────
function buildNginxConfig(d, upstreamUrl) {
  const upstreamHost = upstreamUrl.replace(/^https?:\/\//, '').replace(/\/.*/, '').replace(/:.*/, '');
  const upstreamPort = (() => {
    const m = upstreamUrl.match(/:(\d+)/);
    return m ? m[1] : '8080';
  })();

  return `# ── PTT SSL Proxy (generated by ptt-configure-wss.mjs) ──────────────────────
# Save to: /etc/nginx/sites-available/ptt.${d}
# Then: sudo ln -s /etc/nginx/sites-available/ptt.${d} /etc/nginx/sites-enabled/
#       sudo certbot --nginx -d ptt.${d}
#       sudo nginx -t && sudo systemctl reload nginx

upstream ptt_backend {
    server ${upstreamHost}:${upstreamPort};
}

server {
    listen 80;
    server_name ptt.${d};
    return 301 https://\\$host\\$request_uri;
}

server {
    listen 443 ssl http2;
    server_name ptt.${d};

    # certbot will add ssl_certificate / ssl_certificate_key here

    location / {
        proxy_pass http://ptt_backend;
        proxy_http_version 1.1;
        proxy_set_header Upgrade \\$http_upgrade;
        proxy_set_header Connection "Upgrade";
        proxy_set_header Host \\$host;
        proxy_set_header X-Real-IP \\$remote_addr;
        proxy_set_header X-Forwarded-For \\$proxy_add_x_forwarded_for;
        proxy_set_header X-Forwarded-Proto \\$scheme;
        proxy_read_timeout 3600;
        proxy_send_timeout 3600;
    }

    location /ws {
        proxy_pass http://ptt_backend/ws;
        proxy_http_version 1.1;
        proxy_set_header Upgrade \\$http_upgrade;
        proxy_set_header Connection "Upgrade";
        proxy_set_header Host \\$host;
        proxy_read_timeout 3600;
        proxy_send_timeout 3600;
    }

    location /health {
        proxy_pass http://ptt_backend/health;
    }
}
`;
}

// ─── Build Supabase CLI commands ─────────────────────────────────────────────
function buildSupabaseCommands(wssUrl) {
  return [
    `# 1. Set PTT_WS_URL so the edge function returns wss:// to the client:`,
    `supabase secrets set PTT_WS_URL="${wssUrl}" --project-ref <YOUR_PROJECT_REF>`,
    ``,
    `# 2. Redeploy the ptt-signaling-token edge function to pick up the new secret:`,
    `supabase functions deploy ptt-signaling-token --project-ref <YOUR_PROJECT_REF>`,
    ``,
    `# 3. Verify the health check shows ptt_ws_url = "${wssUrl}":`,
    `curl -s https://<YOUR_PROJECT_REF>.supabase.co/functions/v1/check-railway-health \\`,
    `  -H "Authorization: Bearer <ANON_KEY>" | jq .ptt_ws_url`,
  ].join('\n');
}

async function main() {
  const state = await readSystemState();
  const pttServerUrl = state?.ptt?.server_url || state?.ptt_server_url || 'http://72.61.123.97:8080';

  console.log('\n╔══════════════════════════════════════════════════════════════════════╗');
  console.log('║  PTT wss:// Configuration Helper                                    ║');
  console.log('╚══════════════════════════════════════════════════════════════════════╝\n');

  console.log(`  PTT server URL  : ${pttServerUrl}`);
  console.log(`  Problem         : http:// server → ws:// WebSocket → blocked by HTTPS app`);
  console.log(`  Fix required    : TLS-terminated proxy → wss:// endpoint → set PTT_WS_URL secret\n`);

  // ── Option A: Nginx proxy ──────────────────────────────────────────────────
  if (domain || !nginxOnly) {
    if (!domain) {
      console.log('━━━ OPTION A: nginx + certbot SSL proxy ━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━');
      console.log('  Run with --domain your.domain.com to generate the nginx config.\n');
    } else {
      const wssUrl = `wss://ptt.${domain}/ws`;
      console.log(`━━━ OPTION A: nginx + certbot SSL proxy ━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━`);
      console.log(`  Domain   : ptt.${domain}`);
      console.log(`  wss URL  : ${wssUrl}\n`);

      const nginxConfig = buildNginxConfig(domain, pttServerUrl);
      const outPath = path.resolve(__dirname, '..', 'ops', `nginx-ptt-ssl.conf`);
      await fs.mkdir(path.dirname(outPath), { recursive: true });
      await fs.writeFile(outPath, nginxConfig, 'utf8');
      console.log(`  nginx config written → ops/nginx-ptt-ssl.conf`);
      console.log('  Copy to your VPS and run certbot as shown in the comments.\n');

      console.log('━━━ Supabase secrets to set after nginx is live ━━━━━━━━━━━━━━━━━━━━━━━');
      console.log(buildSupabaseCommands(wssUrl));
      console.log('');
    }
  }

  // ── Option B: Cloudflare Tunnel ───────────────────────────────────────────
  console.log('━━━ OPTION B: Cloudflare Tunnel (zero-config SSL) ━━━━━━━━━━━━━━━━━━━━');
  console.log('  On the PTT server machine:');
  console.log('    curl -L https://github.com/cloudflare/cloudflared/releases/latest/download/cloudflared-linux-amd64 -o cloudflared');
  console.log('    chmod +x cloudflared && ./cloudflared tunnel --url http://localhost:8080');
  console.log('  Cloudflare assigns a *.trycloudflare.com URL with wss:// support.');
  console.log('  Set PTT_WS_URL to wss://<assigned-subdomain>.trycloudflare.com/ws\n');
  console.log(buildSupabaseCommands('wss://<assigned-subdomain>.trycloudflare.com/ws'));
  console.log('');

  // ── Option C: Railway ─────────────────────────────────────────────────────
  console.log('━━━ OPTION C: Deploy PTT server to Railway (built-in TLS) ━━━━━━━━━━━━');
  console.log('  If the PTT server is containerised, deploy it to Railway/Render/Fly.io.');
  console.log('  These platforms provide automatic HTTPS/WSS on a custom domain.');
  console.log('  Then set PTT_WS_URL=wss://<your-railway-domain>/ws in Supabase secrets.\n');

  // ── Minimal test ──────────────────────────────────────────────────────────
  console.log('━━━ Test the fix ━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━');
  console.log('  After setting PTT_WS_URL and redeploying:');
  console.log('    node scripts/ptt-configure-wss.mjs --verify --wss-url <your-wss-url>\n');

  if (args.includes('--verify')) {
    const wssUrl = getArg('--wss-url');
    if (!wssUrl) {
      console.log('  Provide --wss-url wss://... to verify.\n');
    } else {
      const httpUrl = wssUrl.replace('wss://', 'https://').replace('ws://', 'http://').replace('/ws', '/health');
      try {
        const { execSync } = await import('node:child_process');
        const result = execSync(`curl -s --max-time 5 "${httpUrl}"`, { encoding: 'utf8' });
        console.log(`  Health check (${httpUrl}):`);
        console.log(`  ${result.slice(0, 300)}`);
      } catch (e) {
        console.log(`  Health check failed: ${e.message}`);
        console.log('  Ensure the PTT server /health endpoint is reachable via SSL.\n');
      }
    }
  }
}

main().catch(err => {
  console.error('ptt-configure-wss error:', err?.message || err);
  process.exit(1);
});
